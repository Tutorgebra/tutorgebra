import base64
import binascii
import hashlib
import hmac
import json
import logging
import os
import secrets
import time

# Between /api/run (the lesson) and /api/voice (its audio) the lesson travels through the browser, which
# runs it in GeoGebra to read the real values. It goes signed, so /api/voice only synthesizes lessons this
# server generated (never text sent by a client) and no state has to be shared between requests or
# replicas. Set LESSON_SIGNING_KEY to the same secret on every replica.

logger = logging.getLogger('TutorGebraLessonToken')

TOKEN_TTL_SECONDS = 600
MAX_TOKEN_CHARS = 300_000
_key_cache = None


def _key() -> bytes:
    # Read on first use, not at import: app/main.py loads .env after importing the routers
    global _key_cache
    if _key_cache is None:
        configured = os.environ.get("LESSON_SIGNING_KEY", "")
        if configured:
            _key_cache = configured.encode("utf-8")
        else:
            logger.warning("LESSON_SIGNING_KEY is not set: using a random key, so a lesson generated by one "
                           "replica (or before a restart) cannot get its voice from another")
            _key_cache = secrets.token_bytes(32)
    return _key_cache


def _signature(body: str) -> str:
    return hmac.new(_key(), body.encode("ascii"), hashlib.sha256).hexdigest()


def sign_lesson(lesson: dict) -> str:
    payload = json.dumps({"lesson": lesson, "exp": int(time.time()) + TOKEN_TTL_SECONDS},
                         separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    body = base64.urlsafe_b64encode(payload).decode("ascii").rstrip("=")
    return f"{body}.{_signature(body)}"


def verify_lesson(token) -> dict | None:
    """The lesson if the token was signed by this server, is intact and has not expired; otherwise None."""
    if not isinstance(token, str) or len(token) > MAX_TOKEN_CHARS or "." not in token:
        return None
    body, signature = token.rsplit(".", 1)
    try:
        if not hmac.compare_digest(signature, _signature(body)):
            return None
        payload = json.loads(base64.urlsafe_b64decode(body + "=" * (-len(body) % 4)))
    except (ValueError, TypeError, binascii.Error, UnicodeError):
        return None
    if not isinstance(payload, dict) or not isinstance(payload.get("exp"), int) or payload["exp"] < time.time():
        return None
    lesson = payload.get("lesson")
    return lesson if isinstance(lesson, dict) else None
